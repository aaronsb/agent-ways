//! The attend library: the message verbs as typed calls, and the CLI over them.
//!
//! [`verbs`] holds the message verb bodies (send, reply, inbox, peers,
//! status, join, leave, channels). Each takes typed arguments, derives the
//! session afresh, and returns a value: nothing in it prints or exits, so
//! any frontend can call it (ADR-501 items 2 and 4). The `attend`
//! binary is one such frontend; [`cli_main`] is its whole body.
//!
//! Argv parsing is handled by clap-derive (matches ADR-111's pattern for
//! the sibling `ways-cli` binary). The `Cli`/`Commands` definitions and
//! their doc comments live in `cli.rs` — that file is the canonical
//! source for runtime `--help` text AND for the markdown reference at
//! `docs/cli/attend.md` (generated by `bin/gen-docs.rs` via `clap-markdown`).
//! A message verb's one-line summary comes from [`describe`], which every
//! frontend reads.
//!
//! Top-level shape:
//!   - Bare `attend` (no subcommand) prints the agent_fmt banner + help.
//!   - Every `attend X --help` is supplied automatically by clap.
//!   - The match in `cli_main()` maps each enum variant to its `cmd::*::*`
//!     handler. Handlers take typed args directly; the message verbs'
//!     handlers call [`verbs`] and render what it returns.


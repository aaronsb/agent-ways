#!/usr/bin/env python3
"""Regenerate catalog/commands/tldr/ from a pinned tldr-pages release (ADR-706 item 7).

Usage: python3 -I scripts/tldr-extract.py [OUT_DIR]

Downloads the source archive of the pinned tag, checks its SHA-256, and reads
pages.en/{common,linux,osx} straight out of the archive. For each page it keeps
the first description line (the `> ` lines, less "More information", "See
also" and "Note" lines); an alias page ("This command is an alias of `x`.")
takes its target's line. A page found in more than one platform is taken from
the first of common, linux, osx.

Writes OUT_DIR/summaries.tsv (one `page<TAB>summary` line per page, sorted by
page name, `#` lines as a header) and OUT_DIR/NOTICE, the CC BY 4.0
attribution. OUT_DIR defaults to catalog/commands/tldr beside this script's
repository. Nothing is taken from the MIT-licensed scripts/ directory.

To move the pin, change TAG, COMMIT and SHA256 together and rerun.
"""
import hashlib
import io
import os
import re
import sys
import tarfile
import urllib.request

TAG = "v2.3"
COMMIT = "625d3423127117eed2e1613f4a6566b0c2064f41"
SHA256 = "a49c520fa0545286c268c907d6534503ed818a6e5c73cb5cb0c018e237b1f1c4"
URL = f"https://github.com/tldr-pages/tldr/archive/refs/tags/{TAG}.tar.gz"
PLATFORMS = ("common", "linux", "osx")
SKIP = re.compile(r"(More information|See also|Note)\b", re.I)
ALIAS = re.compile(r"This command is an alias of `([^`]+)`")

NOTICE = """\
tldr-pages extract
==================

summaries.tsv in this directory is an extract of tldr-pages
(https://github.com/tldr-pages/tldr), release {tag} (commit {commit}),
taken from pages.en/common, pages.en/linux and pages.en/osx.

Copyright (c) 2014-present the tldr-pages team
(https://github.com/orgs/tldr-pages/people) and contributors
(https://github.com/tldr-pages/tldr/graphs/contributors).

The tldr-pages work is licensed under the Creative Commons Attribution 4.0
International License (CC BY 4.0):
https://creativecommons.org/licenses/by/4.0/

Changes: this file is not the pages themselves. It keeps each page's first
description line, with an alias page taking its target's line, reformatted
as one tab-separated line per page for lookup by the command describer
(ADR-706 item 7). Nothing is taken from tldr-pages' MIT-licensed scripts/
directory.

Regenerate with `make tldr-data` (scripts/tldr-extract.py).
"""


def fetch():
    with urllib.request.urlopen(URL, timeout=60) as r:
        data = r.read()
    got = hashlib.sha256(data).hexdigest()
    if got != SHA256:
        sys.exit(f"tldr-extract: {URL} has SHA-256 {got}, expected {SHA256}")
    return data


def read_pages(data):
    """{(platform, page): text} for pages.en in the pinned platforms."""
    pages = {}
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as tar:
        for m in tar.getmembers():
            parts = m.name.split("/")
            # tldr-<ver>/pages/<platform>/<page>.md; pages.en is a symlink to pages.
            if len(parts) != 4 or parts[1] != "pages" or parts[2] not in PLATFORMS:
                continue
            if not m.isfile() or not parts[3].endswith(".md"):
                continue
            pages[(parts[2], parts[3][:-3])] = tar.extractfile(m).read().decode("utf-8")
    return pages


def first_line(text):
    for line in text.splitlines():
        if line.startswith(">"):
            body = " ".join(line[1:].split())
            if body and not SKIP.match(body):
                return body
    return None


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "catalog", "commands", "tldr")
    pages = read_pages(fetch())
    raw = {}
    for plat in PLATFORMS:
        for (p, name), text in sorted(pages.items()):
            if p == plat and name not in raw:
                line = first_line(text)
                if line:
                    raw[name] = line

    def resolve(name, seen=()):
        line = raw[name]
        m = ALIAS.search(line)
        if not m or name in seen or len(seen) > 3:
            return line
        target = "-".join(m.group(1).split()).lower()
        return resolve(target, seen + (name,)) if target in raw else line

    rows = []
    for name in sorted(raw):
        line = resolve(name)
        if "\t" in name or "\t" in line:
            sys.exit(f"tldr-extract: tab in page {name!r}")
        rows.append(f"{name}\t{line}\n")
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "summaries.tsv"), "w", encoding="utf-8", newline="\n") as f:
        f.write(f"# tldr-pages {TAG} ({COMMIT}), pages.en/{{common,linux,osx}}, CC BY 4.0; see NOTICE.\n")
        f.write("# page<TAB>first description line; generated by scripts/tldr-extract.py, do not edit.\n")
        f.writelines(rows)
    with open(os.path.join(out, "NOTICE"), "w", encoding="utf-8", newline="\n") as f:
        f.write(NOTICE.format(tag=TAG, commit=COMMIT))
    print(f"tldr-extract: {len(rows)} pages from tldr-pages {TAG} -> {out}")


if __name__ == "__main__":
    main()
